import os
from datetime import datetime
from fpdf import FPDF

# Ensure reports directory exists
BASE_DIR = os.path.dirname(os.path.abspath(__file__))
REPORTS_DIR = os.path.join(BASE_DIR, "reports")
os.makedirs(REPORTS_DIR, exist_ok=True)

class AnemiaReportPDF(FPDF):
    def header(self):
        # Logo if available
        logo_path = os.path.join(BASE_DIR, 'static', 'logo.png')
        if os.path.exists(logo_path):
            self.image(logo_path, x=14, y=10, w=30)
            self.set_xy(48, 12)
        else:
            self.set_xy(14, 12)
        
        # Clean title without pathology center name
        self.set_font('Helvetica', 'B', 16)
        self.set_text_color(24, 43, 73)
        self.cell(0, 8, 'ANEMIA DETECTION REPORT', ln=True)
        
        if os.path.exists(logo_path):
            self.set_xy(48, 20)
        else:
            self.set_xy(14, 20)
        self.set_font('Helvetica', '', 10)
        self.set_text_color(100, 110, 125)
        self.cell(0, 5, 'Automated Blood Smear Image & Complete Blood Count (CBC) Evaluation', ln=True)
        
        # Horizontal divider
        self.set_draw_color(220, 226, 235)
        self.set_line_width(0.5)
        self.line(14, 30, 196, 30)
        self.ln(12)

    def footer(self):
        self.set_y(-20)
        self.set_draw_color(220, 226, 235)
        self.set_line_width(0.5)
        self.line(14, 277, 196, 277)
        self.set_font('Helvetica', 'I', 8)
        self.set_text_color(130, 140, 150)
        self.cell(0, 10, 'Electronic Diagnostic Report generated by Anemia Detection System.', align='C')


def generate_pdf_report(patient_name, age, gender, predicted_class, class_prob, rbc_count=None, blood_type=None, hemoglobin=None, mch=None, mcv=None, recommendations=None, morphology=None):
    """
    Generates a high-quality PDF diagnostic lab report and saves it to reports/.
    """
    pdf = AnemiaReportPDF(orientation='P', unit='mm', format='A4')
    pdf.set_auto_page_break(auto=True, margin=20)
    pdf.add_page()
    
    current_date = datetime.now().strftime("%d-%b-%Y %H:%M")
    
    # Report Title Badge
    pdf.set_fill_color(240, 244, 252)
    pdf.set_text_color(15, 76, 129)
    pdf.set_font('Helvetica', 'B', 12)
    pdf.cell(0, 9, '   HEMATOLOGY EXAMINATION REPORT', ln=True, fill=True)
    pdf.ln(3)

    # Patient Demographic Section
    pdf.set_font('Helvetica', 'B', 10)
    pdf.set_text_color(40, 50, 70)
    pdf.cell(95, 6, f'Patient Name:  {patient_name or "N/A"}', border=0)
    pdf.cell(95, 6, f'Report Date:  {current_date}', border=0, ln=True)
    
    pdf.set_font('Helvetica', '', 10)
    pdf.cell(95, 6, f'Age / Sex:  {age or "N/A"} Yrs / {gender or "N/A"}', border=0)
    pdf.cell(95, 6, f'Blood Group:  {blood_type or "Not Specified"}', border=0, ln=True)
    
    pdf.ln(4)
    
    # CBC Parameters Table
    pdf.set_fill_color(235, 240, 248)
    pdf.set_font('Helvetica', 'B', 9)
    pdf.set_text_color(30, 41, 59)
    pdf.cell(60, 7, ' Parameter', border=1, fill=True)
    pdf.cell(40, 7, ' Result Value', border=1, fill=True)
    pdf.cell(45, 7, ' Reference Range', border=1, fill=True)
    pdf.cell(37, 7, ' Status', border=1, fill=True, ln=True)
    
    cbc_rows = [
        ('Hemoglobin (Hb)', f'{hemoglobin} g/dL' if hemoglobin else 'N/A', '12.0 - 16.0 g/dL', 'Low' if hemoglobin and float(hemoglobin or 0) < 12 else 'Normal'),
        ('Total RBC Count', f'{rbc_count} x10^6/uL' if rbc_count else 'N/A', '4.0 - 5.5 x10^6/uL', 'Low' if rbc_count and float(rbc_count or 0) < 4.0 else 'Normal'),
        ('Mean Corpuscular Volume (MCV)', f'{mcv} fL' if mcv else 'N/A', '80.0 - 100.0 fL', 'Low' if mcv and float(mcv or 0) < 80 else ('High' if mcv and float(mcv or 0) > 100 else 'Normal')),
        ('Mean Corpuscular Hb (MCH)', f'{mch} pg' if mch else 'N/A', '27.0 - 33.0 pg', 'Low' if mch and float(mch or 0) < 27 else 'Normal'),
    ]
    
    pdf.set_font('Helvetica', '', 9)
    for param, res, ref, stat in cbc_rows:
        pdf.cell(60, 6, f' {param}', border=1)
        pdf.cell(40, 6, f' {res}', border=1)
        pdf.cell(45, 6, f' {ref}', border=1)
        if stat == 'Low':
            pdf.set_text_color(180, 40, 40)
        elif stat == 'High':
            pdf.set_text_color(190, 100, 20)
        else:
            pdf.set_text_color(30, 120, 50)
        pdf.cell(37, 6, f' {stat}', border=1, ln=True)
        pdf.set_text_color(30, 41, 59)

    pdf.ln(6)

    # Diagnostic Image Findings Section
    pdf.set_fill_color(240, 244, 252)
    pdf.set_text_color(15, 76, 129)
    pdf.set_font('Helvetica', 'B', 11)
    pdf.cell(0, 8, '   BLOOD SMEAR IMAGE MORPHOLOGY & AI PREDICTION', ln=True, fill=True)
    pdf.ln(3)

    # Diagnosis Highlight Box
    pdf.set_fill_color(248, 250, 252)
    pdf.set_draw_color(15, 76, 129)
    pdf.set_line_width(0.4)
    
    pdf.set_font('Helvetica', 'B', 11)
    pdf.set_text_color(15, 76, 129)
    pdf.cell(45, 7, 'Primary Diagnosis:', border=0)
    pdf.set_font('Helvetica', 'B', 12)
    pdf.set_text_color(180, 20, 20)
    pdf.cell(85, 7, f'{predicted_class}', border=0)
    
    pdf.set_font('Helvetica', 'B', 11)
    pdf.set_text_color(40, 50, 70)
    prob_str = f"{class_prob:.2f}%" if isinstance(class_prob, (int, float)) else str(class_prob)
    pdf.cell(0, 7, f'Model Confidence: {prob_str}', border=0, ln=True)

    pdf.ln(2)
    if morphology:
        pdf.set_font('Helvetica', 'B', 9)
        pdf.set_text_color(40, 50, 70)
        pdf.cell(0, 5, 'Morphological Characteristics:', ln=True)
        pdf.set_font('Helvetica', '', 9)
        pdf.set_text_color(70, 80, 95)
        pdf.multi_cell(0, 5, morphology)
        pdf.ln(2)

    if recommendations:
        pdf.set_font('Helvetica', 'B', 9)
        pdf.set_text_color(40, 50, 70)
        pdf.cell(0, 5, 'Clinical Recommendations & Follow-Up:', ln=True)
        pdf.set_font('Helvetica', '', 9)
        pdf.set_text_color(70, 80, 95)
        pdf.multi_cell(0, 5, recommendations)

    pdf.ln(6)

    # Clean Validation Block
    pdf.set_y(245)
    pdf.set_font('Helvetica', 'I', 9)
    pdf.set_text_color(100, 110, 120)
    pdf.cell(110, 5, 'Analyzed by: Anemia Deep Learning Model (VGG16)', border=0)
    pdf.cell(70, 5, 'Status:', border=0, align='R', ln=True)
    pdf.ln(4)
    pdf.set_font('Helvetica', 'B', 10)
    pdf.cell(110, 5, 'Automated AI Diagnostic Evaluation', border=0)
    pdf.cell(70, 5, 'Validated Result', border=0, align='R', ln=True)

    # Safe filename
    clean_name = "".join(c for c in (patient_name or "Patient") if c.isalnum() or c in (' ', '_', '-')).strip()
    clean_name = clean_name.replace(' ', '_')
    pdf_filename = f"{clean_name}_report.pdf"
    pdf_output_path = os.path.join(REPORTS_DIR, pdf_filename)
    
    pdf.output(pdf_output_path)
    return pdf_output_path
